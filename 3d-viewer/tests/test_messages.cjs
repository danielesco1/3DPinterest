// No browser or npm dependencies: validate the cross-origin integration contract.
const assert=require('node:assert/strict');
const fs=require('node:fs');
const vm=require('node:vm');
const path=require('node:path');
const app=fs.readFileSync(path.join(__dirname,'../app.js'),'utf8');
const parent={};
const ctx={window:{parent},location:{origin:'https://storage.googleapis.com'}};
vm.createContext(ctx);
vm.runInContext(app.slice(app.indexOf('function validFlyMessage'),app.indexOf('function cancelFlight')),ctx);
const event={source:parent,origin:'https://danielesco1.github.io',data:{type:'fly',position:[1,2,3]}};
assert.equal(ctx.validFlyMessage(event),true);
assert.equal(ctx.validFlyMessage({...event,origin:ctx.location.origin}),true);
for(const origin of ['null','https://evil.example','https://danielesco1.github.io.evil.example'])assert.equal(ctx.validFlyMessage({...event,origin}),false);
assert.equal(ctx.validFlyMessage({...event,source:{}}),false);
for(const position of [[1,2],[1,2,3,4],[1,NaN,3],[1,Infinity,3],['1',2,3],null])assert.equal(ctx.validFlyMessage({...event,data:{type:'fly',position}}),false);
assert.equal(ctx.validFlyMessage({...event,data:{type:'other',position:[1,2,3]}}),false);
const roomSource=fs.readFileSync(path.join(__dirname,'../../roomboard/js/rooms.js'),'utf8');
const calls=[];
const iframe={src:'https://storage.googleapis.com/roomboard-demo-rooms/scenes/first-room/index.html',contentWindow:{postMessage:(...args)=>calls.push(args)}};
const room={URL,location:{href:'https://danielesco1.github.io/3DPinterest/roomboard/',origin:'https://danielesco1.github.io'},document:{addEventListener(){},getElementById(){return iframe}}};
vm.createContext(room);vm.runInContext(roomSource,room);
assert.equal(room.viewerURL({id:'hiroto-space'}),'https://danielesco1.github.io/3DPinterest/roomboard/viewer.html?room=hiroto-space');
assert.equal(room.viewerURL({id:'h',viewer:iframe.src}),iframe.src);
assert.match(room.viewerURL({id:'h',viewer:'javascript:alert(1)'}),/viewer.html\?room=h$/);
room.flyFrom({dataset:{fly:'1,2,3'}});
assert.equal(calls.length,1);assert.equal(calls[0][1],'https://storage.googleapis.com');
assert.equal(JSON.stringify(calls[0][0]),JSON.stringify({type:'fly',position:[1,2,3]}));
room.flyFrom({dataset:{fly:'NaN,2,3'}});assert.equal(calls.length,1);
iframe.src='https://danielesco1.github.io/3DPinterest/roomboard/viewer.html?room=h';room.flyFrom({dataset:{fly:'1,2,3'}});
assert.equal(calls[1][1],'https://danielesco1.github.io');
console.log('Viewer message and Roomboard URL tests passed');
